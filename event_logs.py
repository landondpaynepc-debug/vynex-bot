"""Staff event logging, without copying sensitive data into Render logs."""
import logging

import discord

from tickets import NO_MENTIONS, TICKET_COLOR

LOG_CHANNEL_ID = 1550300376853520434
MOD_COMMANDS = {'warn', 'timeout', 'untimeout', 'kick', 'ban', 'unban', 'clear'}
AUDIT_ACTIONS = {'kick', 'ban', 'unban', 'member_update', 'message_delete', 'message_bulk_delete'}


def literal(value):
    return discord.utils.escape_markdown(str(value))


class EventLogs:
    def __init__(self, bot, guild_id):
        self.bot, self.guild_id = bot, guild_id

    async def channel(self):
        channel = self.bot.get_channel(LOG_CHANNEL_ID) or await self.bot.fetch_channel(LOG_CHANNEL_ID)
        if not isinstance(channel, discord.TextChannel) or channel.guild.id != self.guild_id:
            raise RuntimeError('Logs channel must be a text channel in the configured server.')
        permissions = channel.permissions_for(channel.guild.me)
        if not permissions.view_channel or not permissions.send_messages:
            raise RuntimeError('Bot needs View Channel and Send Messages in the logs channel.')
        return channel

    async def check(self):
        await self.channel()
        guild = self.bot.get_guild(self.guild_id)
        if guild and not guild.me.guild_permissions.view_audit_log:
            logging.warning('View Audit Log permission is missing; external moderation logs require it.')

    async def send(self, title, body):
        try:
            channel = await self.channel()
            stamp = discord.utils.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')
            for offset in range(0, max(1, len(body)), 3500):
                view = discord.ui.LayoutView(timeout=None)
                view.add_item(discord.ui.Container(
                    discord.ui.TextDisplay(f'## {title}\n{body[offset:offset+3500]}'),
                    discord.ui.Separator(visible=False),
                    discord.ui.TextDisplay(f'-# {stamp}'), accent_colour=TICKET_COLOR))
                await channel.send(view=view, allowed_mentions=NO_MENTIONS)
            return True
        except (discord.HTTPException, RuntimeError) as error:
            # Never print the body: key events contain full license keys.
            logging.error('Discord event log delivery failed (%s); check logs channel permissions.', type(error).__name__)
            return False

    async def key_generated(self, interaction, application, key):
        return await self.send('License key generated',
            f'Generated by: {literal(interaction.user)} ({interaction.user.id})\n'
            f'App: {literal(application)}\nKey: {literal(key)}\n'
            f'Expiry: Lifetime\nChannel: {interaction.channel_id}\nInteraction: {interaction.id}')

    async def command_completed(self, interaction, command):
        if interaction.guild_id != self.guild_id or command.name not in MOD_COMMANDS:
            return
        details = '\n'.join(f'{literal(name)}: {literal(value)}'
                            + (f' ({value.id})' if hasattr(value, 'id') else '')
                            for name, value in interaction.namespace)
        await self.send('Moderation command completed',
            f'Action: /{command.name}\nModerator: {literal(interaction.user)} ({interaction.user.id})\n'
            f'Channel: {interaction.channel_id}\n{details}')

    async def deleted(self, payload):
        if payload.guild_id != self.guild_id or payload.channel_id == LOG_CHANNEL_ID:
            return
        messages = ([payload.cached_message] if hasattr(payload, 'cached_message')
                    else payload.cached_messages)
        cached = {message.id: message for message in messages if message is not None}
        ids = [payload.message_id] if hasattr(payload, 'message_id') else sorted(payload.message_ids)
        for ident in ids:
            message = cached.get(ident)
            body = f'Channel: {payload.channel_id}\nMessage: {ident}\n'
            if message:
                body += f'Author: {literal(message.author)} ({message.author.id})\n'
                body += f'Content:\n{literal(message.content) or "[No text content]"}\n'
                if message.attachments:
                    body += 'Attachments: ' + ', '.join(literal(a.filename) for a in message.attachments) + '\n'
                if message.embeds or message.components:
                    body += '[Message also contained embeds or components.]\n'
            else:
                body += 'Author/content unavailable: message was not in the bot cache.\n'
            body += 'Deleted by: unavailable from this event. Staff deletions may have a separate audit entry.'
            await self.send('Message deleted', body)

    async def audit_entry(self, entry):
        action = entry.action.name
        if entry.guild.id != self.guild_id or action not in AUDIT_ACTIONS:
            return
        # These bot actions already have a command log with the actual moderator.
        if entry.user_id == self.bot.user.id:
            return
        if action == 'member_update' and not any(name == 'timed_out_until' for name, _ in entry.after):
            return
        target = entry.target
        await self.send('Discord moderation audit',
            f'Action: {action}\nModerator: {literal(entry.user or entry.user_id)} ({entry.user_id})\n'
            f'Target: {literal(target)} ({getattr(target, "id", "unknown")})\n'
            f'Reason: {literal(entry.reason or "No reason provided")}\nAudit entry: {entry.id}')
